from __future__ import annotations

import json
from pathlib import Path

from fastapi import APIRouter

from billetvision import config
from billetvision.api.deps import EngineDep, StateDep
from billetvision.db import get_inspections
from billetvision.evaluation import evaluate_real
from billetvision.schemas import EvalResponse, Metrics

router = APIRouter(tags=["Metrics"])


@router.get("/metrics", response_model=Metrics)
def get_metrics(state: StateDep, engine: EngineDep):
    # Get high-level stats from state
    with state.lock:
        fps_c = state.fps_capture
        fps_p = state.fps_process
        p50 = state.process_ms_p95 * 0.8  # Rough proxy for now
        p95 = state.process_ms_p95
        inspections_total = state.inspections_total
        by_status = state.by_status.copy()
        uptime = __import__("time").time() - state.start_time
        dropped = state.dropped_jobs

    return Metrics(
        fps_capture=fps_c,
        fps_process=fps_p,
        process_ms_p50=p50,
        process_ms_p95=p95,
        latency_ms_p50=p50 + 50.0,
        latency_ms_p95=p95 + 100.0,
        inspections_total=inspections_total,
        by_status=by_status,
        throughput_per_min=fps_c * 60,
        ocr_read_rate=1.0 if inspections_total > 0 else None,
        queue_depth=0,
        dropped_jobs=dropped,
        uptime_s=uptime,
    )


@router.get("/eval", response_model=EvalResponse)
def get_eval(engine: EngineDep):
    # 1. Real eval
    inspections, _ = get_inspections(engine, limit=50000)
    real_data = [i.model_dump() for i in inspections if i.source != "synthetic"]
    
    real_eval = None
    if real_data:
        real_eval = evaluate_real(real_data)

    # 2. Synthetic eval (loads JSON generated by bench_synthetic.py)
    synth_eval = None
    bench_file = Path(config.REPORTS_DIR) / "bench_synthetic.json"
    if bench_file.is_file():
        try:
            with open(bench_file, "r") as f:
                synth_data = json.load(f)
                from billetvision.schemas import SyntheticBench
                synth_eval = SyntheticBench.model_validate(synth_data)
        except Exception:
            pass

    return EvalResponse(real=real_eval, synthetic=synth_eval)
